#!/usr/bin/env bash
# ==============================================================================
# Lite Server Monitor (LSM)
# Менеджер обновления
#
# Путь:
#   installer/update.sh
#
# Назначение:
#   Обновление установленной копии LSM:
#
#   1. Получение актуального кода из Git-репозитория.
#   2. Повторный запуск установщика для применения изменений.
#
# Важно:
#
#   Требуются права root.
#   При запуске через "lsm update" проверка прав выполняется
#   в bin/lsm (ensure_root).
#
# ==============================================================================


set -Eeuo pipefail



LSM_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"



#
# Проверка прав root
#

if [[ "${EUID:-$(id -u)}" -ne 0 ]]; then

    echo "Ошибка: обновление требует прав root." >&2

    exit 1

fi



main()
{

    echo "Обновление Lite Server Monitor..."

    echo


    #
    # Получение актуального кода.
    #
    # Отсутствие git-каталога (например, установка из архива)
    # не является ошибкой: установщик обновит файлы из текущего дерева.
    #

    if [[ -d "${LSM_ROOT}/.git" ]]; then

        if ! git -C "${LSM_ROOT}" pull --ff-only; then

            echo "Предупреждение: git pull завершился ошибкой, продолжаем с текущим кодом." >&2

            echo

        fi

    fi


    echo


    "${LSM_ROOT}/installer/install.sh"

}


main "$@"
