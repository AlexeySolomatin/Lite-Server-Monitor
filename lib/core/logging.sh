```bash
#!/usr/bin/env bash
# ==============================================================================
# Lite Server Monitor (LSM)
# Библиотека централизованного логирования
#
# Путь:
#   lib/core/logging.sh
#
# Назначение:
#   Единый механизм регистрации событий LSM.
#
# Поддерживаемые уровни:
#
#   ERROR   - критическая ошибка выполнения LSM
#   FAIL    - проверка выполнена, состояние системы неудовлетворительное
#   WARN    - предупреждение
#   SUCCESS - успешное выполнение операции
#   INFO    - информационное сообщение
#   DEBUG   - отладочная информация
#
# Примеры:
#
#   log_info "Запуск проверки системы"
#
#   log_success "RAID" "RAID1 массив активен"
#
#   log_warn "SMART" "Температура диска 48°C"
#
#   log_fail "UPS" "ИБП отключен"
#
# Формат журнала:
#
#   2026-08-05 09:40:12 [WARN   ] [SMART] Температура диска 48°C
#
# Особенности:
#
#   - единый API для всех компонентов LSM;
#   - запись в /var/log/lsm/lsm.log;
#   - цветной вывод только через colors.sh;
#   - ANSI-цвета не попадают в файл журнала;
#   - ошибки журнала не должны останавливать LSM;
#   - поддерживается старый API:
#       log_info "MESSAGE"
#       log_info "COMPONENT" "MESSAGE"
#
# ==============================================================================


set -Eeuo pipefail



# ==============================================================================
# Защита от повторной загрузки
# ==============================================================================

[[ -n "${LSM_LOGGING_LOADED:-}" ]] && return 0

readonly LSM_LOGGING_LOADED=1



# ==============================================================================
# Определение корня LSM
# ==============================================================================

LSM_ROOT="${LSM_ROOT:-$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)}"

export LSM_ROOT



# ==============================================================================
# Подключение централизованной системы цветов
#
# logging.sh не владеет цветами.
#
# Источник цветов:
#
#   lib/core/colors.sh
#
# Если библиотека недоступна, используются пустые значения.
# Это позволяет logging.sh работать даже в минимальном окружении.
# ==============================================================================

if [[ -f "${LSM_ROOT}/lib/core/colors.sh" ]]; then

    # shellcheck source=/dev/null
    source "${LSM_ROOT}/lib/core/colors.sh"

fi



: "${COLOR_RESET:=}"
: "${COLOR_RED:=}"
: "${COLOR_YELLOW:=}"
: "${COLOR_GREEN:=}"
: "${COLOR_BLUE:=}"
: "${COLOR_MAGENTA:=}"
: "${COLOR_CYAN:=}"



# ==============================================================================
# Настройки логирования
#
# Можно переопределить до загрузки библиотеки:
#
#   LOG_LEVEL=3
#   LSM_LOG_DIR=/custom/path
#   LSM_LOG_FILE=/custom/path/lsm.log
#
# Уровни:
#
#   0 ERROR
#   1 FAIL / WARN
#   2 SUCCESS / INFO
#   3 DEBUG
# ==============================================================================

: "${LOG_LEVEL:=2}"

: "${LSM_LOG_DIR:=/var/log/lsm}"

: "${LSM_LOG_FILE:=${LSM_LOG_DIR}/lsm.log}"



# ==============================================================================
# Числовые уровни
# ==============================================================================

readonly LOG_LEVEL_ERROR=0
readonly LOG_LEVEL_FAIL=1
readonly LOG_LEVEL_WARN=1
readonly LOG_LEVEL_SUCCESS=2
readonly LOG_LEVEL_INFO=2
readonly LOG_LEVEL_DEBUG=3



# ==============================================================================
# Нормализация LOG_LEVEL
#
# Поддерживается:
#
#   LOG_LEVEL=0
#   LOG_LEVEL=1
#   LOG_LEVEL=2
#   LOG_LEVEL=3
#
# а также:
#
#   LOG_LEVEL=ERROR
#   LOG_LEVEL=FAIL
#   LOG_LEVEL=WARN
#   LOG_LEVEL=SUCCESS
#   LOG_LEVEL=INFO
#   LOG_LEVEL=DEBUG
# ==============================================================================

case "${LOG_LEVEL^^}" in

    ERROR)
        LOG_LEVEL="${LOG_LEVEL_ERROR}"
        ;;

    FAIL)
        LOG_LEVEL="${LOG_LEVEL_FAIL}"
        ;;

    WARN|WARNING)
        LOG_LEVEL="${LOG_LEVEL_WARN}"
        ;;

    SUCCESS)
        LOG_LEVEL="${LOG_LEVEL_SUCCESS}"
        ;;

    INFO)
        LOG_LEVEL="${LOG_LEVEL_INFO}"
        ;;

    DEBUG)
        LOG_LEVEL="${LOG_LEVEL_DEBUG}"
        ;;

esac



# ==============================================================================
# Проверка LOG_LEVEL
# ==============================================================================

if ! [[ "${LOG_LEVEL}" =~ ^[0-3]$ ]]; then

    LOG_LEVEL="${LOG_LEVEL_INFO}"

fi



# ==============================================================================
# Получение времени
# ==============================================================================

_log_timestamp()
{
    date '+%Y-%m-%d %H:%M:%S'
}



# ==============================================================================
# Получение цвета для уровня
# ==============================================================================

_log_level_color()
{
    local label="${1:-}"

    case "${label}" in

        ERROR|FAIL)
            printf '%s' "${COLOR_RED}"
            ;;

        WARN)
            printf '%s' "${COLOR_YELLOW}"
            ;;

        SUCCESS)
            printf '%s' "${COLOR_GREEN}"
            ;;

        INFO)
            printf '%s' "${COLOR_BLUE}"
            ;;

        DEBUG)
            printf '%s' "${COLOR_MAGENTA}"
            ;;

        *)
            printf '%s' ""

    esac
}



# ==============================================================================
# Проверка необходимости вывода сообщения
#
# Чем меньше числовой уровень, тем выше приоритет.
#
# LOG_LEVEL=0:
#   ERROR
#
# LOG_LEVEL=1:
#   ERROR
#   FAIL
#   WARN
#
# LOG_LEVEL=2:
#   ERROR
#   FAIL
#   WARN
#   SUCCESS
#   INFO
#
# LOG_LEVEL=3:
#   все сообщения
# ==============================================================================

_log_should_write()
{
    local level="${1}"

    (( LOG_LEVEL >= level ))
}



# ==============================================================================
# Внутренняя функция записи сообщения
#
# Аргументы:
#
#   $1 - числовой уровень
#   $2 - название уровня
#   $3 - компонент
#   $4 - сообщение
# ==============================================================================

_log_write()
{
    local level="${1}"
    local label="${2}"
    local component="${3}"
    local message="${4}"



    # --------------------------------------------------------------------------
    # Проверка уровня
    # --------------------------------------------------------------------------

    if ! _log_should_write "${level}"; then

        return 0

    fi



    # --------------------------------------------------------------------------
    # Время
    # --------------------------------------------------------------------------

    local timestamp

    timestamp="$(_log_timestamp)"



    # --------------------------------------------------------------------------
    # Цвет
    # --------------------------------------------------------------------------

    local color

    color="$(_log_level_color "${label}")"



    # --------------------------------------------------------------------------
    # Консольный вывод
    #
    # Цвет используется только здесь.
    # --------------------------------------------------------------------------

    local console_line

    console_line="$(
        printf '%b%s [%-7s] [%s]%b %s' \
            "${color}" \
            "${timestamp}" \
            "${label}" \
            "${component}" \
            "${COLOR_RESET}" \
            "${message}"
    )"



    # ERROR и FAIL идут в stderr.
    # Остальные сообщения идут в stdout.

    if [[ "${label}" == "ERROR" || "${label}" == "FAIL" ]]; then

        printf '%s\n' "${console_line}" >&2

    else

        printf '%s\n' "${console_line}"

    fi



    # --------------------------------------------------------------------------
    # Подготовка каталога журнала
    #
    # Ошибка создания каталога не должна останавливать LSM.
    # --------------------------------------------------------------------------

    mkdir -p "${LSM_LOG_DIR}" 2>/dev/null || true



    # --------------------------------------------------------------------------
    # Запись в файл
    #
    # Здесь намеренно НЕ используются ANSI-коды.
    # --------------------------------------------------------------------------

    printf '%s [%-7s] [%s] %s\n' \
        "${timestamp}" \
        "${label}" \
        "${component}" \
        "${message}" \
        >> "${LSM_LOG_FILE}" 2>/dev/null || true
}



# ==============================================================================
# Разбор аргументов публичного API
#
# Поддерживаются:
#
#   log_info "Система запущена"
#
# => [INFO] [SYSTEM] Система запущена
#
#
#   log_info "SMART" "Проверка диска"
#
# => [INFO] [SMART] Проверка диска
#
#
# Если передано два и более аргумента:
#
#   первый  = компонент
#   остальные = сообщение
#
# Это позволяет корректно передавать сообщения,
# содержащие пробелы.
# ==============================================================================

_log_parse_args()
{
    local level="${1}"
    local label="${2}"

    shift 2



    local component="SYSTEM"
    local message=""



    if [[ $# -ge 2 ]]; then

        component="${1}"

        shift

        message="$*"


    elif [[ $# -eq 1 ]]; then

        message="${1}"

    fi



    _log_write \
        "${level}" \
        "${label}" \
        "${component}" \
        "${message}"
}



# ==============================================================================
# Публичный API
# ==============================================================================



# ------------------------------------------------------------------------------
# ERROR
#
# Ошибка выполнения самого LSM.
#
# Пример:
#
#   log_error "CONFIG" "Не найден конфигурационный файл"
# ------------------------------------------------------------------------------

log_error()
{
    _log_parse_args \
        "${LOG_LEVEL_ERROR}" \
        "ERROR" \
        "$@"
}



# ------------------------------------------------------------------------------
# FAIL
#
# Проверка выполнена, но состояние системы неудовлетворительное.
#
# Пример:
#
#   log_fail "UPS" "ИБП отключен"
# ------------------------------------------------------------------------------

log_fail()
{
    _log_parse_args \
        "${LOG_LEVEL_FAIL}" \
        "FAIL" \
        "$@"
}



# ------------------------------------------------------------------------------
# WARN
#
# Предупреждение.
#
# Пример:
#
#   log_warn "SMART" "Температура диска 48°C"
# ------------------------------------------------------------------------------

log_warn()
{
    _log_parse_args \
        "${LOG_LEVEL_WARN}" \
        "WARN" \
        "$@"
}



# ------------------------------------------------------------------------------
# SUCCESS
#
# Успешное выполнение операции.
#
# Пример:
#
#   log_success "RAID" "RAID1 массив активен"
# ------------------------------------------------------------------------------

log_success()
{
    _log_parse_args \
        "${LOG_LEVEL_SUCCESS}" \
        "SUCCESS" \
        "$@"
}



# ------------------------------------------------------------------------------
# INFO
#
# Обычная информационная запись.
#
# Пример:
#
#   log_info "SYSTEM" "Запущена проверка системы"
# ------------------------------------------------------------------------------

log_info()
{
    _log_parse_args \
        "${LOG_LEVEL_INFO}" \
        "INFO" \
        "$@"
}



# ------------------------------------------------------------------------------
# DEBUG
#
# Отладочная информация.
#
# Показывается только при:
#
#   LOG_LEVEL=3
# ------------------------------------------------------------------------------

log_debug()
{
    _log_parse_args \
        "${LOG_LEVEL_DEBUG}" \
        "DEBUG" \
        "$@"
}
