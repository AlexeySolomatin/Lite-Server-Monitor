#!/usr/bin/env bash
# ==============================================================================
# Lite Server Monitor (LSM)
# Базовое окружение и общие системные функции
# Путь: lib/core/common.sh
#
# Назначение:
#   Общая библиотека базовых переменных и вспомогательных функций LSM.
#
# Используется:
#   - установщиком;
#   - модулями;
#   - сервисами;
#   - служебными скриптами.
#
# Содержит:
#
#   - определение корня проекта;
#   - загрузку информации о версии;
#   - системные пути LSM;
#   - проверки окружения;
#   - проверку прав root;
#   - проверку наличия команд;
#   - определение поддерживаемой ОС;
#   - проверку доступности сети.
#
# Важно:
#   Данная библиотека не выполняет установку и не изменяет систему.
#   Она только предоставляет общие данные и функции.
# ==============================================================================


set -Eeuo pipefail



#
# Защита от повторного подключения.
#
# Библиотеки LSM подключаются через source.
# Повторная загрузка может привести к повторному объявлению
# переменных и функций.
#

[[ -n "${LSM_COMMON_LOADED:-}" ]] && return 0

readonly LSM_COMMON_LOADED=1



#
# Определение корня проекта.
#
# Если LSM_ROOT уже задан извне,
# используем существующее значение.
#
# Это необходимо для:
#   - установщика;
#   - запуска отдельных компонентов;
#   - тестирования отдельных функций.
#

if [[ -z "${LSM_ROOT:-}" ]]; then


    SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"


    LSM_ROOT="$(cd "${SCRIPT_DIR}/../.." && pwd)"


fi



#
# Экспорт корня проекта.
#
# PROJECT_ROOT используется как универсальное имя
# для внешних скриптов.
#

export LSM_ROOT

export PROJECT_ROOT="${LSM_ROOT}"



#
# Метаданные проекта.
#

export PROJECT_NAME="Lite Server Monitor"



#
# Получение версии проекта.
#
# Версия хранится в отдельном файле:
#
#   /VERSION
#
# Если файл отсутствует,
# используется значение unknown.
#

if [[ -f "${LSM_ROOT}/VERSION" ]]; then


    PROJECT_VERSION="$(tr -d '\r\n' < "${LSM_ROOT}/VERSION")"


else


    PROJECT_VERSION="unknown"


fi



export PROJECT_VERSION



#
# Основные каталоги LSM.
#
# Значения можно переопределить перед подключением:
#
#   LSM_CONFIG_DIR=/custom/path
#
#

#
# Конфигурация:
#
#   /etc/lsm
#
#

export LSM_CONFIG_DIR="${LSM_CONFIG_DIR:-/etc/lsm}"



#
# Логи:
#
#   /var/log/lsm
#
#

export LSM_LOG_DIR="${LSM_LOG_DIR:-/var/log/lsm}"



#
# Рабочие данные:
#
#   /var/lib/lsm
#
#

export LSM_DATA_DIR="${LSM_DATA_DIR:-/var/lib/lsm}"



#
# Проверка запуска от root.
#
# Возвращает:
#
#   0 - root
#   1 - обычный пользователь
#

is_root()
{

    [[ "${EUID:-$(id -u)}" -eq 0 ]]

}



#
# Проверка прав root с сообщением об ошибке.
#
# Используется для операций:
#
#   - установка пакетов;
#   - создание системных каталогов;
#   - настройка сервисов.
#

check_root()
{


    if ! is_root; then



        #
        # Если доступна библиотека логирования,
        # используем стандартный механизм LSM.
        #

        if declare -f log_error >/dev/null 2>&1; then


            log_error \
                "SYSTEM" \
                "Скрипт должен быть запущен с правами root."



        else


            echo \
                "Ошибка: требуется root." >&2



        fi



        exit 1



    fi



}



#
# Проверка существования команды.
#
# Пример:
#
#   if command_exists docker; then
#       ...
#   fi
#

command_exists()
{

    command -v "$1" >/dev/null 2>&1

}



#
# Проверка поддерживаемой операционной системы.
#
# Поддерживаются системы семейства Debian:
#
#   Debian
#   Ubuntu
#   Linux Mint
#   Pop!_OS
#
# Дополнительно проверяется:
#
#   ID_LIKE=debian
#
# для совместимых дистрибутивов.
#

is_supported_os()
{


    #
    # Файл /etc/os-release является стандартным
    # источником информации о Linux-дистрибутиве.
    #

    [[ -f /etc/os-release ]] || return 1



    #
    # shellcheck отключен,
    # так как файл является системным.
    #

    # shellcheck disable=SC1091
    source /etc/os-release



    case "${ID:-}" in


        debian|ubuntu|linuxmint|pop)


            return 0


            ;;



    esac



    #
    # Проверка совместимых Debian-подобных систем.
    #

    [[ "${ID_LIKE:-}" == *debian* ]]

}



#
# Проверка наличия доступа в интернет.
#
# Используется только проверка маршрута наружу.
#
# Не проверяет:
#   - DNS;
#   - HTTP;
#   - доступность репозиториев.
#
# Проверяются публичные IP:
#
#   1.1.1.1  Cloudflare
#   8.8.8.8  Google
#

has_internet()
{


    ping \
        -c 1 \
        -W 2 \
        1.1.1.1 \
        >/dev/null 2>&1 \
    ||
    ping \
        -c 1 \
        -W 2 \
        8.8.8.8 \
        >/dev/null 2>&1


}
