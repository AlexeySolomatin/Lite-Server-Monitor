#!/usr/bin/env bash
# ==============================================================================
# Lite Server Monitor (LSM)
# Библиотека определения ANSI-цветов для консольного вывода
# Путь: lib/core/colors.sh
#
# Назначение:
#   Централизованно определяет ANSI-коды цветов, используемые LSM
#   для вывода информации в консоль.
#
#   Библиотека предоставляет следующие переменные:
#
#     COLOR_RESET   - сброс всех атрибутов форматирования
#     COLOR_BOLD    - полужирный текст
#     COLOR_RED     - красный цвет
#     COLOR_GREEN   - зеленый цвет
#     COLOR_YELLOW  - желтый цвет
#     COLOR_BLUE    - синий цвет
#     COLOR_MAGENTA - пурпурный цвет
#     COLOR_CYAN    - голубой цвет
#     COLOR_WHITE   - белый цвет
#
# Поведение:
#   - Если стандартный вывод не является TTY, цвета отключаются.
#   - Если установлена переменная окружения NO_COLOR, цвета отключаются.
#   - В остальных случаях переменным COLOR_* присваиваются ANSI-коды.
#
# Принцип использования:
#   Другие компоненты LSM не должны самостоятельно определять ANSI-коды.
#   Они используют переменные COLOR_*, предоставляемые этой библиотекой.
#
# Пример:
#
#   printf '%sВажная информация%s\n' \
#       "${COLOR_YELLOW}" \
#       "${COLOR_RESET}"
#
# Совместимость:
#   Bash 4+
#
# ShellCheck:
#   SC2034 отключен, поскольку переменные COLOR_* предназначены
#   для использования вызывающими компонентами и экспортируются
#   в окружение.
# ==============================================================================


# shellcheck disable=SC2034


#
# Защита от повторного подключения
#
# Если библиотека уже была загружена, повторное выполнение файла
# не требуется.
#

[[ -n "${LSM_COLORS_LOADED:-}" ]] && return 0

LSM_COLORS_LOADED=1



#
# Определение цветового режима
#
# Цвета отключаются в двух случаях:
#
#   1. Стандартный вывод не является терминалом (TTY).
#
#      Это позволяет не добавлять управляющие последовательности
#      в перенаправленный вывод, например при записи результата
#      в файл или передаче его в другую программу.
#
#   2. Установлена переменная окружения NO_COLOR.
#
#      В этом случае пользователь явно запрашивает вывод без цветов.
#
# Если ни одно из условий не выполняется, ANSI-цвета включаются.
#

if [[ ! -t 1 || -n "${NO_COLOR:-}" ]]; then


    #
    # Цвета отключены.
    #
    # Пустые значения позволяют использовать COLOR_* в обычных
    # строковых выражениях без необходимости дополнительно проверять,
    # включен ли цветовой вывод.
    #

    COLOR_RESET=""
    COLOR_BOLD=""

    COLOR_RED=""
    COLOR_GREEN=""
    COLOR_YELLOW=""
    COLOR_BLUE=""
    COLOR_MAGENTA=""
    COLOR_CYAN=""
    COLOR_WHITE=""


else


    #
    # Цвета включены.
    #
    # Используется ANSI-C quoting Bash ($'...'), чтобы ANSI-коды
    # преобразовывались в управляющие символы непосредственно
    # при присваивании переменных.
    #
    # Это позволяет безопасно использовать COLOR_* напрямую,
    # например:
    #
    #   printf '%sТекст%s\n' \
    #       "${COLOR_GREEN}" \
    #       "${COLOR_RESET}"
    #
    # Дополнительная интерпретация через echo -e или printf %b
    # для самих цветовых переменных не требуется.
    #

    COLOR_RESET=$'\033[0m'
    COLOR_BOLD=$'\033[1m'

    COLOR_RED=$'\033[31m'
    COLOR_GREEN=$'\033[32m'
    COLOR_YELLOW=$'\033[33m'
    COLOR_BLUE=$'\033[34m'
    COLOR_MAGENTA=$'\033[35m'
    COLOR_CYAN=$'\033[36m'
    COLOR_WHITE=$'\033[37m'


fi



#
# Экспорт цветовых переменных
#
# Переменные экспортируются, чтобы они были доступны компонентам LSM,
# которые подключают или используют общие библиотеки вывода.
#

export COLOR_RESET
export COLOR_BOLD

export COLOR_RED
export COLOR_GREEN
export COLOR_YELLOW
export COLOR_BLUE
export COLOR_MAGENTA
export COLOR_CYAN
export COLOR_WHITE
