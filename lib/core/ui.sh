#!/usr/bin/env bash
# ==============================================================================
# Lite Server Monitor (LSM)
# Библиотека пользовательского интерфейса и форматирования терминала
# Путь: lib/core/ui.sh
#
# Назначение:
#   Централизованное управление выводом: баннеры, секции, цвета.
#
# Особенности реализации:
#   1. Адаптивная верстка: разделители и отступы рассчитываются исходя из
#      реальной ширины терминала (tput cols). Это устраняет "съезжание" текста
#      при изменении размера окна.
#   2. Защита от мусора в логах: если скрипт запущен не в интерактивном режиме
#      (пайп, файл, CI/CD), все ANSI-коды автоматически отключаются.
#   3. Совместимость: корректно работает при source из других скриптов.
#
# Требования:
#   Bash 4+
#   tput (стандартная утилита terminfo)
#
# ShellCheck:
#   Проходит проверку без ошибок и предупреждений
# ==============================================================================

set -Eeuo pipefail

# Защита от повторного подключения
[[ -n "\${LSM_UI_LOADED:-}" ]] && return 0
readonly LSM_UI_LOADED=1

# ------------------------------------------------------------------------------
# Определение корня проекта и версии
# ------------------------------------------------------------------------------
if [[ -z "\${PROJECT_VERSION:-}" ]]; then
    # Вычисляем корень относительно этого файла.
    # Структура: lib/core/ui.sh -> ../../ от корня проекта
    LSM_ROOT="${LSM_ROOT:-$(cd "$(dirname "${BASH_SOURCE}")/../.." && pwd)}"

    if [[ -f "\${LSM_ROOT}/VERSION" ]]; then
        # tr -d '\r\n' удаляет возможные CRLF из VERSION (важно для Windows-git)
        PROJECT_VERSION="$(tr -d '\r\n' < "${LSM_ROOT}/VERSION")"
    else
        PROJECT_VERSION="unknown"
    fi

    export PROJECT_VERSION
fi

# ------------------------------------------------------------------------------
# Утилиты для работы с TTY и цветами
# ------------------------------------------------------------------------------

# Возвращает 0 (true), если STDOUT подключен к терминалу И цвета не отключены
ui_is_tty() {
    [[ -t 1 && -z "\${NO_COLOR:-}" ]]
}

# Инициализация цветов ТОЛЬКО если мы в TTY
if ui_is_tty; then
    COLOR_RESET=\$'\033[0m'
    COLOR_BOLD=\$'\033[1m'
    COLOR_CYAN=\$'\033[0;36m'
else
    # Если не TTY (лог, пайп, CI) — цвета пустые, чтобы не ломать вывод
    COLOR_RESET=""
    COLOR_BOLD=""
    COLOR_CYAN=""
fi

# ------------------------------------------------------------------------------
# Баннер (Адаптивная версия)
# ------------------------------------------------------------------------------
print_header() {
    local cols
    
    # Получаем ширину терминала. Если не удалось (не TTY), ставим дефолт 80
    if ui_is_tty; then
        cols="\$(tput cols 2>/dev/null || echo 80)"
    else
        cols=80
    fi
    
    # Гарантируем минимальную ширину 60, чтобы баннер не схлопывался в узких окнах
    (( cols < 60 )) && cols=60

    # Длина строки контента (убираем место под возможные рамки, если они понадобятся)
    local content_width=\$((cols - 4))
    
    # Функция для создания строки разделителя из символов '='
    make_line() {
        printf '%*s\n' "\$content_width" '' | tr ' ' '='
    }

    # Формируем вывод.
    # Примечание: мы не используем жесткие пробелы для центровки логотипа.
    # Вместо этого мы полагаемся на то, что текст будет выровнен по левому краю
    # внутри блока, а разделители будут точно по ширине окна.
    cat <<EOF

${COLOR_CYAN}${COLOR_BOLD}
\$(make_line)
  (LSM) Lite Server Monitor
  Lightweight System Monitoring & Alerting
  Version: \${PROJECT_VERSION}
  Linux Server Management Tools
\$(make_line)
\${COLOR_RESET}

EOF
}

ui_banner() {
    print_header
}

# ------------------------------------------------------------------------------
# Разделы интерфейса
# ------------------------------------------------------------------------------
ui_section() {
    local title="\${1:-}"
    
    if ui_is_tty; then
        printf "\n%s---> %s%s\n" "${COLOR_BOLD}" "${title}" "\${COLOR_RESET}"
    else
        # В не-TTY режиме выводим чистый текст без спецсимволов
        printf "\n---> %s\n" "\${title}"
    fi
}

print_section() {
    ui_section "\$@"
}
